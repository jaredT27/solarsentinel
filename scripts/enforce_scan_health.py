#!/usr/bin/env python3
"""Apply the GitHub Actions health policy to a completed market scan."""

from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any


def evaluate_scan_health(
    payload: dict[str, Any],
    *,
    scan_exit: int,
    started_at: float,
    allow_nyiso_degraded: bool,
) -> tuple[bool, str]:
    """Return whether the workflow should pass and a human-readable reason."""
    try:
        generated_at = datetime.fromisoformat(str(payload["generated_at"]))
        if generated_at.tzinfo is None:
            generated_at = generated_at.replace(tzinfo=UTC)
    except (KeyError, TypeError, ValueError):
        return False, "Scan status has no valid generated_at timestamp"

    # Prevent a crashed scan from being excused by yesterday's degraded file.
    if generated_at.timestamp() + 5 < started_at:
        return False, "Scan status is stale and was not generated by this run"

    markets = payload.get("markets")
    if not isinstance(markets, list) or not markets:
        return False, "Scan status contains no market results"
    if not all(isinstance(market, dict) for market in markets):
        return False, "Scan status contains an invalid market result"

    unhealthy = [market for market in markets if not market.get("healthy")]
    healthy_markets = payload.get("healthy_markets")
    total_markets = payload.get("total_markets")
    if not isinstance(healthy_markets, int) or not isinstance(total_markets, int):
        return False, "Scan status contains invalid market counts"
    if total_markets != len(markets) or healthy_markets != len(markets) - len(unhealthy):
        return False, "Scan status market counts are inconsistent"

    if scan_exit == 0:
        if not unhealthy and payload.get("status") == "healthy":
            return True, "All configured markets are healthy"
        return False, "Scanner exited successfully but its health record is inconsistent"

    nyiso_only = (
        allow_nyiso_degraded
        and payload.get("status") == "degraded"
        and len(unhealthy) == 1
        and unhealthy[0].get("iso") == "NYISO"
        and unhealthy[0].get("error") == "Empty queue returned"
        and healthy_markets == total_markets - 1
    )
    if nyiso_only:
        return True, "NYISO is temporarily unavailable; all other markets are healthy"

    failed_markets = ", ".join(str(market.get("iso", "unknown")) for market in unhealthy)
    return False, f"Unhealthy markets require attention: {failed_markets or 'unknown'}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--status-file", type=Path, default=Path("data/scan_status.json"))
    parser.add_argument("--scan-exit", type=int, required=True)
    parser.add_argument("--started-at", type=float, required=True)
    parser.add_argument("--allow-nyiso-degraded", action="store_true")
    args = parser.parse_args()

    try:
        payload = json.loads(args.status_file.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"::error title=Invalid scan status::{exc}")
        return 1

    passed, reason = evaluate_scan_health(
        payload,
        scan_exit=args.scan_exit,
        started_at=args.started_at,
        allow_nyiso_degraded=args.allow_nyiso_degraded,
    )
    annotation = "warning" if passed and args.scan_exit else "notice" if passed else "error"
    print(f"::{annotation} title=Solar Sentinel health::{reason}")
    return 0 if passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
